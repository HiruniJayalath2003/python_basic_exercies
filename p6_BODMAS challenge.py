A= 10+5*2
B= (10+5)*2

#print answers
print(A)
print(B)

# The results are different because the calculations use BODMAS differently.
# BODMAS stands for (), of, /, * + -
# In calculation A, multiplication happens first, then the addition.
# In calculation B, the brackets are solved first, and then the multiplication.
# That's why we get different answers.
